/**
 * Generates public GTFS row types and their compile-time conformance fixture
 * from the compiled schema manifest. Called by `pnpm row-types:generate`;
 * `--check` is used by `pnpm row-types:check` and `pnpm test`.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

import { compiledTableRegistry } from '../src/schema/table-registry.ts';

const outputUrl = new URL('../src/schema/row-types.ts', import.meta.url);
const typeTestOutputUrl = new URL(
  '../test/types/generated-row-types.ts',
  import.meta.url,
);
const check = process.argv.includes('--check');
const specificationLabels = {
  'gtfs-schedule': 'GTFS Schedule',
  'gtfs-realtime': 'GTFS Realtime',
  'gtfs-plus': 'GTFS Plus',
  'gtfs-ride': 'GTFS Ride',
  'gtfs-to-html': 'GTFS to HTML',
  tods: 'TODS',
  'tods-v1': 'TODS v1',
  tides: 'TIDES',
};
const realtimeTypeByTable = {
  alert_entity_selectors: 'RealtimeAlertEntitySelector',
  alert_time_ranges: 'RealtimeAlertTimeRange',
  alerts: 'RealtimeAlert',
  realtime_feed_entities: 'RealtimeFeedEntity',
  realtime_feeds: 'RealtimeFeed',
  realtime_shapes: 'RealtimeShape',
  realtime_snapshots: 'RealtimeSnapshot',
  realtime_stops: 'RealtimeStop',
  trip_modifications: 'RealtimeTripModifications',
  trip_update_stop_time_updates: 'RealtimeStopTimeUpdate',
  trip_updates: 'RealtimeTripUpdate',
  vehicle_positions: 'RealtimeVehiclePosition',
};

function filenameTypeName(filename) {
  const match = /^(?<stem>[a-z\d]+(?:_[a-z\d]+)*)\.(?:txt|csv|geojson)$/u.exec(
    filename,
  );
  if (match?.groups?.stem === undefined) {
    throw new Error(
      `Cannot derive a public row type from filename ${filename}`,
    );
  }
  return match.groups.stem
    .split('_')
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join('');
}

const fileTypesBySpecification = new Map();
const generatedTypeNames = new Map();
const nonFileTables = [];

for (const [registryKey, table] of Object.entries(compiledTableRegistry)) {
  if (table.filename === null) {
    nonFileTables.push(table);
    continue;
  }

  const typeName =
    table.tableName === 'tods_vehicles'
      ? 'TodsVehicles'
      : filenameTypeName(table.filename);
  const existingFilename = generatedTypeNames.get(typeName);
  if (existingFilename !== undefined) {
    throw new Error(
      `Filenames ${existingFilename} and ${table.filename} both generate ${typeName}`,
    );
  }
  generatedTypeNames.set(typeName, table.filename);

  const entries = fileTypesBySpecification.get(table.specification) ?? [];
  entries.push({ tableName: table.tableName, registryKey, typeName });
  fileTypesBySpecification.set(table.specification, entries);
}

const unmappedNonFileTables = nonFileTables.filter(
  (table) => realtimeTypeByTable[table.tableName] === undefined,
);
if (unmappedNonFileTables.length > 0) {
  throw new Error(
    `Non-file-backed tables need explicit canonical types: ${unmappedNonFileTables
      .map((table) => table.tableName)
      .join(', ')}`,
  );
}
const unknownRealtimeMappings = Object.keys(realtimeTypeByTable).filter(
  (tableName) => !nonFileTables.some((table) => table.tableName === tableName),
);
if (unknownRealtimeMappings.length > 0) {
  throw new Error(
    `Realtime type mappings reference unknown tables: ${unknownRealtimeMappings.join(', ')}`,
  );
}

const fileTypeSections = [...fileTypesBySpecification].map(
  ([
    specification,
    entries,
  ]) => `// ${specificationLabels[specification] ?? specification}
${entries
  .map(
    ({ registryKey, typeName }) =>
      `export type ${typeName} = GtfsDefaultRow<typeof tables.${registryKey}>;`,
  )
  .join('\n')}`,
);
const realtimeTypes = nonFileTables
  .map(
    (table) =>
      `export type ${realtimeTypeByTable[table.tableName]} = GtfsStoredTableRow<'${table.tableName}'>;`,
  )
  .join('\n');

const source = `// This file is generated by scripts/generate-row-types.mjs. Do not edit it directly.

import type { GtfsDatabase } from './database.ts';
import type { GtfsDefaultRow } from './define-table.ts';
import type * as tables from './tables/index.ts';

/** Direct database row, including generated columns and unknown-field storage. */
export type GtfsStoredTableRow<TableName extends keyof GtfsDatabase> =
  GtfsDatabase[TableName];

type NonNullableField<
  TableName extends keyof GtfsDatabase,
  FieldName extends keyof GtfsDatabase[TableName],
> = NonNullable<GtfsDatabase[TableName][FieldName]>;

// Filename-based types describe repository results when select is omitted.
${fileTypeSections.join('\n\n')}

// Non-file-backed GTFS Realtime persistence and projection rows use explicit names.
${realtimeTypes}

export type GtfsRealtimeTripScheduleRelationship = NonNullableField<
  'trip_updates',
  'schedule_relationship'
>;
export type GtfsRealtimeStopTimeScheduleRelationship = NonNullableField<
  'trip_update_stop_time_updates',
  'schedule_relationship'
>;
export type GtfsRealtimeOccupancyStatus = NonNullableField<
  'vehicle_positions',
  'occupancy_status'
>;
export type GtfsRealtimeWheelchairAccessible = NonNullableField<
  'vehicle_positions',
  'vehicle_wheelchair_accessible'
>;
export type GtfsRealtimeDropOffPickupType = NonNullableField<
  'trip_update_stop_time_updates',
  'pickup_type'
>;
export type GtfsRealtimeAlertCause = NonNullableField<'alerts', 'cause'>;
export type GtfsRealtimeAlertEffect = NonNullableField<'alerts', 'effect'>;
export type GtfsRealtimeAlertSeverity = NonNullableField<
  'alerts',
  'severity_level'
>;
export type GtfsRealtimeVehicleStopStatus = NonNullableField<
  'vehicle_positions',
  'current_status'
>;
export type GtfsRealtimeCongestionLevel = NonNullableField<
  'vehicle_positions',
  'congestion_level'
>;
`;

const generatedFileTypes = [...fileTypesBySpecification.values()].flat();
const canonicalRealtimeTypes = nonFileTables.map((table) => ({
  tableName: table.tableName,
  typeName: realtimeTypeByTable[table.tableName],
}));
const typeTestSource = `// This file is generated by scripts/generate-row-types.mjs. Do not edit it directly.

import type {
${generatedFileTypes.map(({ typeName }) => `  ${typeName},`).join('\n')}
${canonicalRealtimeTypes.map(({ typeName }) => `  ${typeName},`).join('\n')}
  GtfsStoredTableRow,
} from '../../src/schema/row-types.ts';
import type { GtfsImportResult } from '../../src/schedule/import/result.ts';
import type { GtfsDefaultRow } from '../../src/schema/define-table.ts';
import type * as tables from '../../src/schema/tables/index.ts';
import type * as RootApi from 'gtfs';
import type * as SchemaApi from 'gtfs/schema';

type Equal<Left, Right> =
  (<Value>() => Value extends Left ? 1 : 2) extends
  (<Value>() => Value extends Right ? 1 : 2) ? true : false;
type Assert<Value extends true> = Value;

type FileRowTypeAssertions = [
${generatedFileTypes
  .map(
    ({ registryKey, typeName }) =>
      `  Assert<Equal<${typeName}, GtfsDefaultRow<typeof tables.${registryKey}>>>,
  Assert<Equal<${typeName}, RootApi.${typeName}>>,
  Assert<Equal<${typeName}, SchemaApi.${typeName}>>,`,
  )
  .join('\n')}
];
void (null as unknown as FileRowTypeAssertions);

type RealtimeRowTypeAssertions = [
${canonicalRealtimeTypes
  .map(
    ({ tableName, typeName }) =>
      `  Assert<Equal<${typeName}, GtfsStoredTableRow<'${tableName}'>>>,`,
  )
  .join('\n')}
];
void (null as unknown as RealtimeRowTypeAssertions);
void (null as unknown as GtfsImportResult);
`;

const formatted = await format(source, {
  filepath: fileURLToPath(outputUrl),
  singleQuote: true,
});
const formattedTypeTest = await format(typeTestSource, {
  filepath: fileURLToPath(typeTestOutputUrl),
  singleQuote: true,
});

if (check) {
  const [current, currentTypeTest] = await Promise.all([
    readFile(outputUrl, 'utf8'),
    readFile(typeTestOutputUrl, 'utf8'),
  ]);
  if (current !== formatted || currentTypeTest !== formattedTypeTest) {
    throw new Error(
      'Generated row types are stale. Run `npm run row-types:generate`.',
    );
  }
} else {
  await Promise.all([
    writeFile(outputUrl, formatted),
    writeFile(typeTestOutputUrl, formattedTypeTest),
  ]);
}
