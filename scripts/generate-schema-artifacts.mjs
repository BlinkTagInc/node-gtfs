/**
 * Generates field/repository reference pages and backend DDL snapshots from
 * source metadata. Called by `pnpm schema:generate`; `--check` is read-only
 * and runs as part of `pnpm generated:check` in CI and the test suite.
 */
import { renderFieldReferences } from './lib/field-reference.mjs';
import {
  createKyselySchemaSnapshot,
  createSqliteSchemaSnapshot,
} from './lib/schema-snapshots.mjs';
import { writeGeneratedFile } from './lib/generated-file.mjs';
import { format, resolveConfig } from 'prettier';
import * as domainTables from '../src/schema/tables/index.ts';

const check = process.argv.includes('--check');
const formatting = await resolveConfig(
  new URL('../package.json', import.meta.url),
);
const artifacts = await renderFieldReferences();
artifacts.set(
  'src/schema/managed-tables.ts',
  await format(
    `// Generated by scripts/generate-schema-artifacts.mjs. Do not edit by hand.
import * as definitions from './tables/index.ts';
import { tableStoragePolicies } from '../database/storage/table-policy.ts';
import { toManagedGtfsTable } from '../database/storage/table-definition.ts';

${Object.keys(domainTables)
  .map(
    (name) =>
      `export const ${name} = toManagedGtfsTable(definitions.${name}, tableStoragePolicies[definitions.${name}.tableName]);`,
  )
  .join('\n')}
`,
    { ...formatting, parser: 'typescript' },
  ),
);
artifacts.set(
  'test/fixtures/sqlite-schema.json',
  `${JSON.stringify(createSqliteSchemaSnapshot(), null, 2)}\n`,
);
for (const dialect of ['sqlite', 'postgres', 'mysql']) {
  artifacts.set(
    `test/fixtures/kysely-${dialect}-schema.json`,
    await format(JSON.stringify(await createKyselySchemaSnapshot(dialect)), {
      ...formatting,
      parser: 'json',
    }),
  );
}
for (const [filename, contents] of artifacts) {
  await writeGeneratedFile(
    new URL(`../${filename}`, import.meta.url),
    contents,
    { check },
  );
}
